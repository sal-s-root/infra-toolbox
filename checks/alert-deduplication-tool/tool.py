#!/usr/bin/env python3
"""Group alerts by a caller-selected identity label set."""
import argparse
import collections
import configparser
import datetime
import fnmatch
import hashlib
import ipaddress
import itertools
import json
import math
import re
import statistics
import sys
import urllib.parse


def evaluate(data):
    """Evaluate supplied infrastructure metadata without changing remote systems."""
    if not isinstance(data, dict):
        raise ValueError("input must be a JSON object")
    keys = sorted(set(data['identity_labels']))
    if not keys:
        raise ValueError('at least one identity label is required')
    groups = collections.defaultdict(list)
    for alert in data['alerts']:
        labels = alert['labels']
        if any(key not in labels for key in keys):
            raise ValueError('alert missing identity label')
        identity = tuple((key,str(labels[key])) for key in keys)
        groups[identity].append(alert['id'])
    return {'groups':[{'identity':dict(identity),'alert_ids':sorted(ids)} for identity,ids in sorted(groups.items())]}


def _check_finite(value):
    if isinstance(value, float) and not math.isfinite(value):
        raise ValueError("numeric input must be finite")
    if isinstance(value, dict):
        for child in value.values():
            _check_finite(child)
    elif isinstance(value, list):
        for child in value:
            _check_finite(child)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input", nargs="?", default="-", help="JSON input file, or - for stdin")
    args = parser.parse_args(argv)
    try:
        if args.input == "-":
            data = json.load(sys.stdin)
        else:
            with open(args.input, encoding="utf-8") as source:
                data = json.load(source)
        _check_finite(data)
        result = evaluate(data)
        print(json.dumps(result, indent=2, sort_keys=True, allow_nan=False))
        return 0
    except (OSError, ValueError, TypeError, KeyError, OverflowError, configparser.Error) as error:
        print("Input error: " + str(error), file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
