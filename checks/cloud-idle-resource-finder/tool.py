#!/usr/bin/env python3
"""Find resource observations below a caller-defined utilization threshold."""
import argparse
import collections
import configparser
import datetime
import fnmatch
import hashlib
import ipaddress
import itertools
import json
import math
import re
import statistics
import sys
import urllib.parse


def evaluate(data):
    """Evaluate supplied infrastructure metadata without changing remote systems."""
    if not isinstance(data, dict):
        raise ValueError("input must be a JSON object")
    threshold = float(data.get('cpu_threshold_percent',5))
    minimum = int(data.get('minimum_observation_hours',168))
    if not 0<=threshold<=100 or minimum<1:
        raise ValueError('invalid threshold or observation window')
    candidates = []
    for row in data['resources']:
        cpu,hours = float(row['average_cpu_percent']),int(row['observation_hours'])
        if not 0<=cpu<=100 or hours<0:
            raise ValueError('invalid utilization observation')
        if hours>=minimum and cpu<threshold:
            candidates.append(row['id'])
    return {'candidates_for_review':sorted(candidates)}


def _check_finite(value):
    if isinstance(value, float) and not math.isfinite(value):
        raise ValueError("numeric input must be finite")
    if isinstance(value, dict):
        for child in value.values():
            _check_finite(child)
    elif isinstance(value, list):
        for child in value:
            _check_finite(child)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input", nargs="?", default="-", help="JSON input file, or - for stdin")
    args = parser.parse_args(argv)
    try:
        if args.input == "-":
            data = json.load(sys.stdin)
        else:
            with open(args.input, encoding="utf-8") as source:
                data = json.load(source)
        _check_finite(data)
        result = evaluate(data)
        print(json.dumps(result, indent=2, sort_keys=True, allow_nan=False))
        return 0
    except (OSError, ValueError, TypeError, KeyError, OverflowError, configparser.Error) as error:
        print("Input error: " + str(error), file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
